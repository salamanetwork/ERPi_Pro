SUPPORTED_PRINT_LANGUAGES = ("en", "ar", "ur", "fa", "fr", "es", "de", "tr", "hi")
RTL_LANGUAGES = frozenset({"ar", "ur", "fa"})


def normalize_print_language(value, default="en"):
    code = (value or "").strip().lower()[:2]
    return code if code in SUPPORTED_PRINT_LANGUAGES else default


def is_rtl_language(language):
    return normalize_print_language(language) in RTL_LANGUAGES


def print_direction(language):
    return "rtl" if is_rtl_language(language) else "ltr"


