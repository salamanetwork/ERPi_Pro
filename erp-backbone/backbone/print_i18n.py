def print_strings(language):
    code = normalize_print_language(language)
    return PRINT_STRINGS.get(code, PRINT_STRINGS["en"])


def print_text(language, key):
    bundle = print_strings(language)
    return bundle.get(key) or PRINT_STRINGS["en"].get(key, key)


def print_status(language, status, fallback=None):
    code = normalize_print_language(language)
    key = f"status_{(status or '').strip().lower()}"
    bundle = print_strings(code)
    if key in bundle:
        return bundle[key]
    return fallback if fallback is not None else (status or "").replace("_", " ").title()
